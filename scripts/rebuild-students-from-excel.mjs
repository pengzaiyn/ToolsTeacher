function loadEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return;
  const content = fs.readFileSync(filePath, 'utf8');
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let val = trimmed.slice(eq + 1).trim();
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    if (!process.env[key]) process.env[key] = val;
  }
}

function slug(value) {
  return String(value ?? '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/đ/g, 'd')
    .replace(/[^a-z0-9]/g, '');
}

function classKey(name) {
  return String(name ?? '')
    .normalize('NFC')
    .trim()
    .replace(/\s+/g, ' ')
    .toLowerCase();
}

function fallbackStudentEmail(fullName, code) {
  const parts = fullName.trim().split(/\s+/);
  const given = slug(parts[parts.length - 1] ?? '') || 'sv';
  const cleanCode = slug(code);
  return `${given}${cleanCode.slice(-8)}${SCHOOL_DOMAIN}`;
}

function sanitizeEmail(raw) {
  let cleaned = String(raw ?? '').trim().replace(/\.+$/, '');
  if (!cleaned) return null;
  if (!cleaned.includes('@')) {
    cleaned = cleaned.replace(/(gmail\.com|caodangvietmyhanoi\.edu\.vn|hnet\.edu\.vn)$/i, '@$1');
  }
  const atIndex = cleaned.indexOf('@');
  if (atIndex <= 0) return null;
  const localRaw = cleaned.slice(0, atIndex);
  const domainRaw = cleaned.slice(atIndex + 1).trim().toLowerCase().replace(/\.+$/, '');
  const local = localRaw
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/đ/g, 'd')
    .replace(/\s+/g, '')
    .replace(/[^a-z0-9._+-]/g, '');
  if (!local || !domainRaw || !domainRaw.includes('.')) return null;
  return `${local}@${domainRaw}`;
}

function parseExcel(excelPath) {
  const wb = XLSX.readFile(excelPath);
  const ws = wb.Sheets[wb.SheetNames[0]];
  const rows = XLSX.utils.sheet_to_json(ws, { defval: '' });

  const studentsByCode = new Map();
  const classesByKey = new Map();
  const usedEmails = new Map();
  let autoGeneratedEmails = 0;
  let fixedEmails = 0;

  for (const r of rows) {
    const code = String(r['Mã sinh viên'] ?? '').trim().replace(/\s+/g, '').toUpperCase();
    const fullName = String(r['Họ và tên'] ?? '').trim().replace(/\s+/g, ' ');
    if (!code || !fullName) continue;

    const rawClass = String(r['Lớp'] ?? '').trim().replace(/\s+/g, ' ');
    const isRealClass = Boolean(rawClass) && !PLACEHOLDER_CLASSES.has(rawClass.toLowerCase());
    const cKey = isRealClass ? classKey(rawClass) : null;
    if (isRealClass && cKey && !classesByKey.has(cKey)) {
      classesByKey.set(cKey, { name: rawClass, class_key: cKey });
    }

    const status = String(r['Tháng 11/2026'] ?? '').trim();
    const isActive = !INACTIVE_STATUSES.has(status.toLowerCase());
    const rawEmail = String(r['Email'] ?? '').trim();
    const sanitized = sanitizeEmail(rawEmail);

    let stu = studentsByCode.get(code);
    if (!stu) {
      let email = sanitized;
      if (!email) {
        email = fallbackStudentEmail(fullName, code);
        autoGeneratedEmails += 1;
      } else if (email !== rawEmail.toLowerCase()) {
        fixedEmails += 1;
      }

      if (usedEmails.has(email) && usedEmails.get(email) !== code) {
        email = fallbackStudentEmail(fullName, code);
        if (usedEmails.has(email) && usedEmails.get(email) !== code) {
          email = `${slug(code)}${SCHOOL_DOMAIN}`;
        }
        autoGeneratedEmails += 1;
      }
      usedEmails.set(email, code);

      stu = {
        student_code: code,
        full_name: fullName,
        email,
        education_system: String(r['Hệ đào tạo'] ?? '').trim() || null,
        major: String(r['Ngành đào tạo'] ?? '').trim() || null,
        cohort: String(r['Khóa'] ?? '').trim() || null,
        initial_cohort: String(r['Khóa ban đầu'] ?? '').trim() || null,
        academic_status: status || null,
        status_reason: String(r['Lý do'] ?? '').trim() || null,
        status_note: String(r['Ghi chú'] ?? '').trim() || null,
        is_active: isActive,
        classes: [],
      };
      studentsByCode.set(code, stu);
    } else {
      // Nếu SV học song song nhiều lớp, ưu tiên giữ trạng thái đang hoạt động nếu một dòng đang học
      if (isActive && !stu.is_active) {
        stu.is_active = true;
        if (status) stu.academic_status = status;
      }
    }

    if (isRealClass && cKey && !stu.classes.some((c) => c.class_key === cKey)) {
      stu.classes.push({ name: rawClass, class_key: cKey });
    }
  }

  return {
    totalRows: rows.length,
    students: Array.from(studentsByCode.values()),
    classes: Array.from(classesByKey.values()),
    autoGeneratedEmails,
    fixedEmails,
  };
}

async function runPool(items, concurrency, worker) {
  let index = 0;
  const runners = Array.from({ length: concurrency }, async () => {
    while (index < items.length) {
      const current = index;
      index += 1;
      await worker(items[current], current);
    }
  });
  await Promise.all(runners);
}

async function main() {
  loadEnvFile(path.resolve('.env'));
  loadEnvFile(path.resolve('.env.local'));

  console.log(`Đang đọc file Excel: ${DEFAULT_EXCEL_PATH}`);
  const parsed = parseExcel(DEFAULT_EXCEL_PATH);
  const multiClassStudents = parsed.students.filter((s) => s.classes.length > 1).length;
  const activeCount = parsed.students.filter((s) => s.is_active).length;
  const lockedCount = parsed.students.length - activeCount;

  console.log('--- TỔNG HỢP DỮ LIỆU ---');
  console.log(`Tổng dòng Excel:       ${parsed.totalRows}`);
  console.log(`Sinh viên duy nhất:    ${parsed.students.length}`);
  console.log(`  - Đang hoạt động:    ${activeCount}`);
  console.log(`  - Tự động khóa:      ${lockedCount}`);
  console.log(`  - Học song song >=2 lớp: ${multiClassStudents}`);
  console.log(`Số lớp học thật:       ${parsed.classes.length}`);
  console.log(`Email chuẩn hóa lại:   ${parsed.fixedEmails}`);
  console.log(`Email tự sinh mới:     ${parsed.autoGeneratedEmails}`);

  if (!EXECUTE) {
    console.log('\n[DRY-RUN] Chưa ghi vào Supabase. Thêm cờ --execute để thực thi.');
    return;
  }

  const supabaseUrl = process.env.VITE_SUPABASE_URL;
  const serviceRoleKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
  const defaultPassword = process.env.DEFAULT_STUDENT_PASSWORD || '123@123a';

  if (!supabaseUrl || !serviceRoleKey) {
    console.error('Thiếu VITE_SUPABASE_URL hoặc SUPABASE_SERVICE_ROLE_KEY trong .env / .env.local');
    process.exit(1);
  }

  const admin = createClient(supabaseUrl, serviceRoleKey, {
    auth: { persistSession: false, autoRefreshToken: false },
  });

  console.log('\n1. Đang dọn dữ liệu lớp học & điểm danh & bài tập test cũ...');
  for (const table of ['attendance_sessions', 'assignments', 'timetable_entries', 'enrollments', 'classes']) {
    const { error } = await admin.from(table).delete().neq('id', '00000000-0000-0000-0000-000000000000');
    if (error) throw new Error(`Lỗi xóa bảng ${table}: ${error.message}`);
  }

  console.log('2. Đang xóa toàn bộ tài khoản sinh viên cũ (giữ nguyên admin & teacher)...');
  const { data: oldStudents, error: oldErr } = await admin
    .from('profiles')
    .select('id')
    .eq('role', 'student');
  if (oldErr) throw new Error(`Lỗi lấy danh sách sinh viên cũ: ${oldErr.message}`);

  await runPool(oldStudents ?? [], 8, async (row) => {
    const { error } = await admin.auth.admin.deleteUser(row.id);
    if (error) console.warn(`Cảnh báo xóa user ${row.id}: ${error.message}`);
  });
  console.log(`   Đã xóa ${(oldStudents ?? []).length} tài khoản sinh viên cũ.`);

  console.log('3. Đang tạo lại toàn bộ danh sách lớp từ file Excel...');
  const classIdByKey = new Map();
  for (let i = 0; i < parsed.classes.length; i += 200) {
    const chunk = parsed.classes.slice(i, i + 200);
    const { data, error } = await admin
      .from('classes')
      .upsert(chunk, { onConflict: 'class_key' })
      .select('id, class_key');
    if (error) throw new Error(`Lỗi tạo lớp: ${error.message}`);
    for (const c of data ?? []) {
      classIdByKey.set(c.class_key, c.id);
    }
  }
  console.log(`   Đã tạo ${classIdByKey.size} lớp học.`);

  console.log('4. Đang tạo tài khoản & hồ sơ sinh viên mới...');
  const enrollmentRows = [];
  const failures = [];
  let done = 0;

  await runPool(parsed.students, 8, async (stu) => {
    try {
      const primaryClass = stu.classes[0] ?? null;
      const { data: created, error: authErr } = await admin.auth.admin.createUser({
        email: stu.email,
        password: defaultPassword,
        email_confirm: true,
        app_metadata: { role: 'student' },
        ban_duration: stu.is_active ? 'none' : '876000h',
      });
      if (authErr || !created.user) {
        throw new Error(authErr?.message ?? 'createUser failed');
      }

      const { error: profErr } = await admin.from('profiles').insert({
        id: created.user.id,
        email: stu.email,
        full_name: stu.full_name,
        role: 'student',
        is_active: stu.is_active,
        student_code: stu.student_code,
        class_name: primaryClass ? primaryClass.name : null,
        class_key: primaryClass ? primaryClass.class_key : null,
        education_system: stu.education_system,
        major: stu.major,
        cohort: stu.cohort,
        initial_cohort: stu.initial_cohort,
        academic_status: stu.academic_status,
        status_reason: stu.status_reason,
        status_note: stu.status_note,
      });
      if (profErr) {
        await admin.auth.admin.deleteUser(created.user.id);
        throw new Error(profErr.message);
      }

      for (const cls of stu.classes) {
        const classId = classIdByKey.get(cls.class_key);
        if (classId) {
          enrollmentRows.push({ class_id: classId, student_id: created.user.id });
        }
      }
    } catch (err) {
      failures.push({
        student_code: stu.student_code,
        full_name: stu.full_name,
        email: stu.email,
        error: err instanceof Error ? err.message : String(err),
      });
    } finally {
      done += 1;
      if (done % 250 === 0 || done === parsed.students.length) {
        console.log(`   Tiến độ: ${done}/${parsed.students.length} sinh viên...`);
      }
    }
  });

  console.log('5. Đang ghi danh đa lớp vào enrollments...');
  for (let i = 0; i < enrollmentRows.length; i += 500) {
    const chunk = enrollmentRows.slice(i, i + 500);
    const { error } = await admin
      .from('enrollments')
      .upsert(chunk, { onConflict: 'class_id,student_id' });
    if (error) throw new Error(`Lỗi ghi danh enrollments: ${error.message}`);
  }

  console.log('\n--- HOÀN TẤT ---');
  console.log(`Thành công: ${parsed.students.length - failures.length}/${parsed.students.length} sinh viên`);
  console.log(`Tổng ghi danh lớp: ${enrollmentRows.length}`);
  if (failures.length > 0) {
    const failPath = path.resolve('scripts/rebuild-failures.json');
    fs.writeFileSync(failPath, JSON.stringify(failures, null, 2), 'utf8');
    console.log(`Có ${failures.length} lỗi, đã lưu chi tiết tại ${failPath}`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});

